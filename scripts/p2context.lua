-- ============================================================================
-- scripts/p2context.lua
-- 《零点之后》第二关「雪线诊所」P2 会话状态上下文（桥接层）
--
-- 职责：为 P2Controller 及其功能模块提供「当前 P2 会话态」的统一访问入口。
--       本文件只持有当前会话态表的引用，不构造状态结构、不依赖任何业务模块、
--       不含任何 DEBUG 逻辑、不执行任何顶层代码。
--
-- 设计约束（V1.0-04C-A）：
--   - 不 require P2State（状态结构由 p2state.lua 负责）
--   - 不 require RunState（继承数据由调用方组装后传入）
--   - 不含 DEBUG 逻辑（DEBUG 注入由流程控制器处理，仅在此 Set 成品状态）
--   - 无顶层执行（仅定义模块接口）
--
-- Get() 未初始化时返回 nil；Set() 覆盖 current，使各 P2 模块始终取得最新会话。
-- ============================================================================

local current = nil

-- 保存当前 P2 会话态表引用。
-- 调用方：流程控制器创建或重建 P2 会话后调用。
function Set(state)
    current = state
end

-- 取得当前 P2 会话态表；未初始化时返回 nil（与 GetP2() 行为一致）。
function Get()
    return current
end

return {
    Set = Set,
    Get = Get,
}
